-- Тред, адресованный cto, показывал человеку бейдж «ждут вас».
--
-- Колонка полностью повторяет question_messages.addressed_to: CSV
-- идентификаторов участников, пусто — «всем участникам, кроме автора вопроса».
-- Существующие строки получают пустое значение, то есть прежнее поведение.
