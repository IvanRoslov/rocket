-- Майлстоны для внешних агентов (задача #1023, спека v2). Майлстон — корневая
-- задача БЕЗ проекта, которую берёт постоянный агент: «выше проектов», с теми же
-- доками, журналом и вопросными тредами, что и у обычной задачи.
--
-- Признак хранится явной колонкой, а не выводится из «project_id пуст»: project_id
-- объявлен NOT NULL ещё в 0001, у майлстона он '' (та же конвенция, что у
-- agents.project_id — '' значит «вне проекта»), а '' от NULL здесь не отличить без
-- пересборки таблицы. Явная колонка переживёт и будущие фичи, где проект станет
-- необязательным и у обычных задач.
ALTER TABLE tasks ADD COLUMN milestone INTEGER NOT NULL DEFAULT 0;

-- id постоянного агента, взявшего майлстон (NULL — не взят). Ровно одно из
-- session_id (оркестратор фичи) и assigned_role (агент майлстона) может быть
-- непустым: пути взаимоисключающие.
ALTER TABLE tasks ADD COLUMN assigned_role TEXT;

CREATE INDEX idx_tasks_milestone ON tasks(milestone, assigned_role);
