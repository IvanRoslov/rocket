-- Свежесть PR-статуса сессии (задача #1180). До этой колонки нельзя было
-- отличить «PR действительно открыт» от «мы перестали опрашивать GitHub про эту
-- сессию час назад»: pr_state замерзал молча, и `rocket task show` показывал
-- уже смерженные PR как открытые (реальный случай — задача #1087, шесть PR).
--
-- Колонка хранит unix-время ПОСЛЕДНЕГО УСПЕШНОГО опроса GitHub по этой сессии,
-- а не время изменения pr_state: именно «когда мы последний раз смотрели»
-- отвечает на вопрос «можно ли верить тому, что показано». NULL = ни одного
-- успешного опроса ещё не было.
ALTER TABLE sessions ADD COLUMN pr_checked_at INTEGER;

-- Опрос ghpoller теперь выбирает живые сессии ПЛЮС любые сессии с PR в
-- нетерминальном состоянии, независимо от state сессии.
CREATE INDEX idx_sessions_pr_poll ON sessions(kind, pr_number, pr_state);
